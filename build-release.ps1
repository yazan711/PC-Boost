<#
.SYNOPSIS
    Automated build, test, Authenticode signing, and release packaging pipeline for PC Boost.
.DESCRIPTION
    1. Builds CleanRamBoosterApp and CleanRamBoosterApp.Tests in Release mode.
    2. Runs the full automated test suite (fails build if any test fails).
    3. Syncs framework-dependent ReadyToRun_App binaries.
    4. Publishes self-contained win-x64 ReadyToRun bundle into CleanRamBoosterApp\publish\win-x64.
    5. Authenticode-signs CleanRamBoosterApp.exe and setup.exe using signtool.exe (if installed)
       or built-in PowerShell Set-AuthenticodeSignature with a commercial or local .pfx certificate.
    6. Refreshes "Portable PC Boost", "Portable PC Boost.zip", "ReadyToRun_App.zip", and "Source Code".
    7. Compiles standalone setup.exe via Inno Setup 6 (ISCC.exe) and verifies all Authenticode signatures.
#>
param(
    [switch]$SkipTests,
    [switch]$SkipZip,
    [switch]$NoSign,
    [string]$CertPath = $env:SIGN_CERT_PFX,
    [string]$CertPassword = $env:SIGN_CERT_PASSWORD,
    [string]$TimestampUrl = "http://timestamp.digicert.com"
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $root

# Auto-discover local certificate generated by scripts\Setup-CodeSigning.ps1 if none passed
if (-not $NoSign -and [string]::IsNullOrWhiteSpace($CertPath)) {
    $localPfx = Join-Path $root "certs\PCBoostCodeSign.pfx"
    $localPwd = Join-Path $root "certs\PCBoostCodeSign.pass"
    if (Test-Path $localPfx) {
        $CertPath = $localPfx
        if ([string]::IsNullOrWhiteSpace($CertPassword) -and (Test-Path $localPwd)) {
            $CertPassword = (Get-Content $localPwd -Raw).Trim()
        }
    }
}

function Find-SignTool {
    $cmd = Get-Command signtool.exe -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    $kits = Get-ChildItem "C:\Program Files (x86)\Windows Kits\10\bin\*\x64\signtool.exe" -ErrorAction SilentlyContinue |
            Sort-Object FullName -Descending | Select-Object -First 1
    if ($kits) { return $kits.FullName }
    return $null
}

$script:LoadedCert = $null
if (-not $NoSign -and -not [string]::IsNullOrWhiteSpace($CertPath) -and (Test-Path $CertPath)) {
    $flags = [System.Security.Cryptography.X509Certificates.X509KeyStorageFlags]::Exportable -bor
             [System.Security.Cryptography.X509Certificates.X509KeyStorageFlags]::PersistKeySet
    $script:LoadedCert = New-Object System.Security.Cryptography.X509Certificates.X509Certificate2($CertPath, $CertPassword, $flags)
    Write-Host "Authenticode Signing Enabled: $($script:LoadedCert.Subject) [$($script:LoadedCert.Thumbprint)]" -ForegroundColor Green
}

function Invoke-CodeSign {
    param([string]$FilePath)
    if ($NoSign -or -not $script:LoadedCert -or -not (Test-Path $FilePath)) { return }

    $signtool = Find-SignTool
    if ($signtool) {
        Write-Host "Signing (signtool.exe): $FilePath ..." -ForegroundColor Cyan
        $signArgs = @("sign", "/f", $CertPath, "/fd", "SHA256", "/tr", $TimestampUrl, "/td", "SHA256")
        if (-not [string]::IsNullOrWhiteSpace($CertPassword)) { $signArgs += @("/p", $CertPassword) }
        $signArgs += $FilePath
        & $signtool @signArgs
        if ($LASTEXITCODE -ne 0) {
            # Retry without external timestamp server if offline
            Write-Warning "Timestamp server unreachable; retrying offline SHA-256 signature..."
            $offlineArgs = @("sign", "/f", $CertPath, "/fd", "SHA256")
            if (-not [string]::IsNullOrWhiteSpace($CertPassword)) { $offlineArgs += @("/p", $CertPassword) }
            $offlineArgs += $FilePath
            & $signtool @offlineArgs
            if ($LASTEXITCODE -ne 0) { throw "signtool failed for $FilePath" }
        }
    } else {
        Write-Host "Signing (PowerShell Set-AuthenticodeSignature SHA-256): $FilePath ..." -ForegroundColor Cyan
        $sig = Set-AuthenticodeSignature -FilePath $FilePath -Certificate $script:LoadedCert -HashAlgorithm SHA256 -TimestampServer $TimestampUrl -ErrorAction SilentlyContinue
        if (-not $sig -or -not $sig.SignerCertificate) {
            $sig = Set-AuthenticodeSignature -FilePath $FilePath -Certificate $script:LoadedCert -HashAlgorithm SHA256
        }
        if (-not $sig -or -not $sig.SignerCertificate) {
            throw "Authenticode signing failed for $FilePath"
        }
    }
}

Write-Host "=== [1/7] Stopping any running PC Boost instance ===" -ForegroundColor Cyan
Get-Process CleanRamBoosterApp -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
Start-Sleep -Milliseconds 300

Write-Host "=== [2/7] Building Solution (Release) ===" -ForegroundColor Cyan
dotnet build "PCBoost.sln" -c Release --nologo
if ($LASTEXITCODE -ne 0) { throw "Solution build failed." }

if (-not $SkipTests) {
    Write-Host "=== [3/7] Running Automated Test Suite ===" -ForegroundColor Cyan
    dotnet run --project "CleanRamBoosterApp.Tests\CleanRamBoosterApp.Tests.csproj" -c Release --no-build --nologo
    if ($LASTEXITCODE -ne 0) { throw "Automated test suite failed!" }
} else {
    Write-Host "=== [3/7] Skipping tests (-SkipTests) ===" -ForegroundColor Yellow
}

Write-Host "=== [4/7] Syncing & Signing ReadyToRun_App ===" -ForegroundColor Cyan
New-Item -ItemType Directory -Force -Path "ReadyToRun_App\Resources" | Out-Null
Copy-Item "CleanRamBoosterApp\bin\Release\net8.0-windows\CleanRamBoosterApp.*" "ReadyToRun_App\" -Force
Copy-Item "CleanRamBoosterApp\Resources\app.*" "ReadyToRun_App\Resources\" -Force
Copy-Item "CleanRamBoosterApp\Resources\app.ico" "ReadyToRun_App\app.ico" -Force
Copy-Item "CleanRamBoosterApp\Resources\app_icon.png" "ReadyToRun_App\app_icon.png" -Force
Invoke-CodeSign (Join-Path $root "ReadyToRun_App\CleanRamBoosterApp.exe")

Write-Host "=== [5/7] Publishing Self-Contained win-x64 ReadyToRun Bundle ===" -ForegroundColor Cyan
$publishDir = Join-Path $root "CleanRamBoosterApp\publish\win-x64"
if (Test-Path $publishDir) { Remove-Item $publishDir -Recurse -Force }
dotnet publish "CleanRamBoosterApp\CleanRamBoosterApp.csproj" -c Release -r win-x64 --self-contained true -p:PublishReadyToRun=true -o $publishDir --nologo
if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed." }

Invoke-CodeSign (Join-Path $publishDir "CleanRamBoosterApp.exe")

Write-Host "=== [6/7] Updating Portable PC Boost, Zips & Source Code ===" -ForegroundColor Cyan
$portableDir = Join-Path $root "Portable PC Boost"
if (Test-Path $portableDir) { Remove-Item $portableDir -Recurse -Force }
New-Item -ItemType Directory -Force -Path $portableDir | Out-Null
Copy-Item "$publishDir\*" $portableDir -Recurse -Force

if (-not $SkipZip) {
    $portableZip = Join-Path $root "Portable PC Boost.zip"
    if (Test-Path $portableZip) { Remove-Item $portableZip -Force }
    Compress-Archive -Path "$portableDir\*" -DestinationPath $portableZip -CompressionLevel Optimal

    $r2rZip = Join-Path $root "ReadyToRun_App.zip"
    if (Test-Path $r2rZip) { Remove-Item $r2rZip -Force }
    Compress-Archive -Path "ReadyToRun_App\*" -DestinationPath $r2rZip -CompressionLevel Optimal
}

$srcOut = Join-Path $root "Source Code"
if (Test-Path $srcOut) { Remove-Item $srcOut -Recurse -Force }
New-Item -ItemType Directory -Force -Path $srcOut | Out-Null

foreach ($dir in @("CleanRamBoosterApp", "CleanRamBoosterApp.Tests", "scripts")) {
    $srcProj = Join-Path $root $dir
    if (Test-Path $srcProj) {
        $dstProj = Join-Path $srcOut $dir
        robocopy $srcProj $dstProj /E /XD bin obj publish .vs /NFL /NDL /NJH /NJS /NC /NS | Out-Null
    }
}
Copy-Item "PCBoost.sln", "build-release.ps1", ".gitignore", "README.md", "HANDOVER.md" $srcOut -ErrorAction SilentlyContinue

Write-Host "=== [7/7] Compiling & Signing Inno Setup 6 Installer (setup.exe) ===" -ForegroundColor Cyan
$isccCandidates = @(
    (Get-Command iscc.exe -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Source -ErrorAction SilentlyContinue),
    "$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe",
    "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe",
    "$env:ProgramFiles\Inno Setup 6\ISCC.exe"
) | Where-Object { $_ -and (Test-Path $_) }

$iscc = $isccCandidates | Select-Object -First 1
if (-not $iscc) {
    Write-Warning "Inno Setup 6 (ISCC.exe) not found. Skipping setup.exe build."
} else {
    & $iscc "CleanRamBoosterApp\Installer\PCBoostSetup.iss"
    if ($LASTEXITCODE -ne 0) { throw "Inno Setup compilation failed." }
    Invoke-CodeSign (Join-Path $root "setup.exe")
}

Write-Host "`n=== Release Checksums (SHA-256) ===" -ForegroundColor Green
$artifacts = @(
    "ReadyToRun_App\CleanRamBoosterApp.exe",
    "ReadyToRun_App\CleanRamBoosterApp.dll",
    "Portable PC Boost\CleanRamBoosterApp.exe",
    "setup.exe"
) | Where-Object { Test-Path $_ }
Get-FileHash $artifacts -Algorithm SHA256 | Format-Table Algorithm, Hash, Path -AutoSize

Write-Host "=== Authenticode Signature Verification ===" -ForegroundColor Green
$signedExes = @(
    "ReadyToRun_App\CleanRamBoosterApp.exe",
    "Portable PC Boost\CleanRamBoosterApp.exe",
    "setup.exe"
) | Where-Object { Test-Path $_ }
foreach ($exe in $signedExes) {
    $s = Get-AuthenticodeSignature $exe
    $subj = if ($s.SignerCertificate) { $s.SignerCertificate.Subject } else { "Unsigned" }
    $ts = if ($s.TimeStamperCertificate) { $s.TimeStamperCertificate.Subject } else { "No external timestamp" }
    Write-Host ("  {0,-42} | Status={1,-14} | Signer={2} | TS={3}" -f $exe, $s.Status, $subj, $ts)
}
Write-Host "`nRELEASE PIPELINE SUCCEEDED!" -ForegroundColor Green
